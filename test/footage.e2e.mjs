import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { mkdtemp, mkdir, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { chromium } from 'playwright';
import { startServer } from '../server/index.mjs';

const execute = promisify(execFile), directory = await mkdtemp(join(tmpdir(), 'slowview-browser-'));
const artifacts = resolve('artifacts'); await mkdir(artifacts, { recursive: true });
const video = join(directory, 'fixture-tecnica.mp4');
// This test pattern verifies the editor. It is never added to the user's catalogue.
await execute('ffmpeg', ['-v', 'error', '-y', '-f', 'lavfi', '-i', 'color=c=darkseagreen:s=1280x720:r=25:d=5.92', '-f', 'lavfi', '-i', 'sine=frequency=440:duration=5.92', '-c:v', 'libx264', '-preset', 'ultrafast', '-threads', '2', '-c:a', 'aac', '-shortest', video]);
const password = 'senha-exclusiva-do-teste-de-edicao';
const service = await startServer({ port: 0, dataDir: join(directory, 'data'), dashboardPassword: password, enableWorker: false });
let browser;
try {
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_EXECUTABLE || '/usr/bin/chromium', chromiumSandbox: process.env.CHROMIUM_NO_SANDBOX !== '1', args: ['--disable-dev-shm-usage', '--disable-gpu'] });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  await page.goto(service.baseUrl);
  await page.getByLabel('Senha', { exact: true }).fill(password);
  await page.getByRole('button', { name: 'Entrar no ateliê' }).click();
  await page.getByRole('heading', { name: 'Um lugar para desacelerar.' }).waitFor();
  await page.getByRole('heading', { name: 'O primeiro cenário vem de uma filmagem.' }).waitFor();
  await page.screenshot({ path: join(artifacts, 'footage-library.png'), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'Trem', exact: true }).click();
  await page.getByRole('heading', { name: 'Viagens de trem.' }).waitFor();
  assert.equal(await page.getByText('Em preparação', { exact: true }).count(), 3);
  await page.getByLabel('Buscar percurso, cidade ou trem').fill('Bodo');
  await page.getByRole('heading', { name: 'Nordlandsbanen', exact: true }).waitFor();
  assert.equal(await page.getByText('Em preparação', { exact: true }).count(), 1);
  await page.getByRole('button', { name: 'Biblioteca', exact: true }).click();
  await page.getByRole('button', { name: 'Preparar importação da amostra', exact: true }).click();
  assert.match(await page.getByLabel('Nome do material').inputValue(), /Trem na neve/);
  assert.equal(await page.getByLabel('Origem e licença').inputValue(), 'pexels');
  assert.equal(await page.getByLabel('Conferi os direitos para editar e publicar este material.').isChecked(), false);
  assert.match(await page.getByLabel(/^Link direto do arquivo/).inputValue(), /videos\.pexels\.com\/video-files\/3563086\//);
  await page.getByRole('button', { name: 'Fechar importação' }).click();
  await page.getByRole('button', { name: 'Adicionar material', exact: true }).click();
  await page.locator('input[type=file]').setInputFiles(video);
  await page.getByLabel('Nome do material').fill('Fixture técnica — não é filmagem real');
  await page.getByLabel('Autor e créditos').fill('Teste automatizado');
  await page.getByLabel('Conferi os direitos para editar e publicar este material.').check();
  await page.getByRole('button', { name: 'Adicionar à biblioteca' }).click();
  await page.getByRole('button', { name: 'Assistir e editar' }).click();
  const source = page.getByLabel('Filmagem original: Fixture técnica — não é filmagem real');
  await source.evaluate(video => new Promise(resolve => { if (video.readyState >= 1) resolve(); else video.addEventListener('loadedmetadata', resolve, { once: true }); }));
  assert.equal(await source.evaluate(video => video.paused && !video.autoplay && video.volume <= .3), true);
  const startInput = page.getByLabel('Início (segundos)'), endInput = page.getByLabel('Fim (segundos)');
  assert.equal(Number(await endInput.inputValue()), 5.92, 'the default endpoint keeps the complete source duration');
  assert.equal(await endInput.evaluate(input => input.checkValidity()), true, 'a fractional source duration must not block export');
  await startInput.fill('0.04');
  assert.equal(await startInput.evaluate(input => input.checkValidity()), true, 'fractional starting positions are accepted');
  await startInput.fill('0');
  await page.getByLabel('Nome do vídeo').fill('Trecho técnico de teste');
  // Export the default complete selection: the reported bug required users to
  // change a valid source duration (e.g. 25.92s) just to submit this form.
  await page.getByRole('button', { name: 'Exportar trecho em MP4' }).click();
  await page.getByText('Pronto para assistir', { exact: true }).waitFor({ timeout: 60000 });
  const result = page.getByLabel('Edição: Trecho técnico de teste');
  await result.evaluate(video => new Promise(resolve => { if (video.readyState >= 1) resolve(); else video.addEventListener('loadedmetadata', resolve, { once: true }); }));
  assert.equal(await result.evaluate(video => video.paused && !video.autoplay && Math.abs(video.duration - 5.92) < .1), true);
  await page.getByRole('button', { name: 'Assistir sem distrações' }).click();
  const dialog = page.getByRole('dialog'); await dialog.waitFor();
  const quietVideo = dialog.locator('video');
  assert.equal(await quietVideo.evaluate(video => video.paused && !video.autoplay && video.volume <= .2), true);
  await dialog.getByLabel('Volume', { exact: true }).focus(); await page.keyboard.press('Home');
  assert.equal(await quietVideo.evaluate(video => video.muted && video.volume === 0), true);
  await dialog.getByLabel('Pausa automática').selectOption('5');
  await quietVideo.evaluate(video => video.play()); await page.waitForTimeout(500); assert.equal(await quietVideo.evaluate(video => video.paused), false);
  await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'detached' });
  assert.equal(await result.evaluate(video => video.paused), true);
  const downloadWait = page.waitForEvent('download'); await page.getByRole('button', { name: 'Baixar créditos' }).click();
  const credits = await downloadWait; assert.match(credits.suggestedFilename(), /^creditos-.*\.txt$/);
  const link = await page.getByRole('link', { name: 'Baixar MP4' }).getAttribute('href');
  assert.equal((await fetch(`${service.baseUrl}${link}`, { headers: { Range: 'bytes=0-31' } })).status, 206);
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', { name: 'Biblioteca', exact: true }).click();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.screenshot({ path: join(artifacts, 'footage-library-mobile.png'), fullPage: true });
  await page.getByRole('button', { name: 'Sair do ateliê' }).click();
  await page.getByRole('button', { name: 'Entrar no ateliê' }).waitFor();
  assert.equal((await fetch(`${service.baseUrl}/api/footage/assets`)).status, 401);
  assert.deepEqual(errors, []);
  console.log('✓ Login, catálogo Trem, amostra com direitos pendentes, upload, exportação com duração fracionária, edição FFmpeg, player sem autoplay, volume, pausa opcional, Escape, créditos, Range, mobile e logout.');
} finally { await browser?.close(); await service.close(); await rm(directory, { recursive: true, force: true }); }
